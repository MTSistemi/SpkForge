// The root guard of zt-syno-net and the DSM boot-up task that runs it.
//
// DSM 7 refuses any root step or file capability in a third-party package
// ("ctrl-script and executable section should not exist", "tool capabilities
// should not exist"), so the only root actor is a Task Scheduler task. The
// install wizard creates it through the admin's own DSM session.
//
// Security rule: root never executes a file the package user can modify. The
// whole guard script is stored inside the task (DSM keeps it root-owned); at
// boot the task writes it to /run (root-owned tmpfs) and starts it there. The
// guard never follows symlinks inside the package's directories.
//
// Every 30 seconds the guard:
//   - loads tun and makes /dev/net/tun usable;
//   - grants CAP_NET_ADMIN/CAP_NET_RAW to the package's zerotier-one when it is
//     new (install, upgrade) and records it in /run/<pkg>.caps for the package;
//   - migrates the identity of an older ZeroTier package once;
//   - keeps the identity owned by the package user;
//   - starts the package when DSM wants it running and it is not.

export interface GuardOptions {
  /** Package name, e.g. "zt-syno-net". */
  pkg: string;
  /** Package user from conf/privilege, e.g. "zt-syno-net" or "sc-zt-syno-net". */
  user: string;
  /** Path of the zerotier-one executable, or "per-family" for zerotier-one-<family> picked by uname -m. */
  daemon: 'per-family' | string;
}

export const GUARD_VERSION = 1;
export const TASK_NAME = 'zt-syno-net';
const HEREDOC = 'ZT_SYNO_NET_GUARD_EOF';

function daemonResolver(options: GuardOptions): string {
  if (options.daemon !== 'per-family') return `echo "${options.daemon}"`;
  return [
    'case "$(uname -m)" in',
    '        x86_64|amd64) f=x86_64 ;; aarch64|arm64|armv8*) f=armv8 ;;',
    '        armv7*|armv6*|arm) f=armv7 ;; i686|i586|i486|i386|x86) f=i686 ;; *) f=unknown ;;',
    '    esac',
    '    echo "$TARGET/bin/zerotier-one-$f"',
  ].join('\n');
}

export function guardScript(options: GuardOptions): string {
  return `#!/bin/sh
# ${options.pkg} guard v${GUARD_VERSION} (root). Generated by SpkForge, installed by the
# "${TASK_NAME}" boot-up task. https://github.com/MTSistemi/SpkForge
PKG="${options.pkg}"
PKG_USER="${options.user}"
PKG_DIR="/var/packages/$PKG"
TARGET="$PKG_DIR/target"
HOME_DIR="$PKG_DIR/var"
MARK="/run/$PKG.caps"
LOG="/var/log/$PKG-guard.log"
PIDF="/run/$PKG-guard.pid"
OLD_DIRS="/var/packages/zerotier/var /volume1/@appdata/zerotier"
export PATH=/sbin:/bin:/usr/sbin:/usr/bin:/usr/syno/sbin:/usr/syno/bin

log() {
    echo "$(date '+%Y-%m-%d %H:%M:%S') $*" >> "$LOG"
    if [ "$(wc -l < "$LOG")" -gt 500 ]; then tail -n 300 "$LOG" > "$LOG.tmp" && mv -f "$LOG.tmp" "$LOG"; fi
}

daemon_path() {
    ${daemonResolver(options)}
}

installed() { [ -f "$PKG_DIR/INFO" ] && [ -d "$TARGET/bin" ]; }

plain_file() { [ -f "$1" ] && [ ! -L "$1" ]; }

ensure_tun() {
    lsmod | grep -qw tun || insmod /lib/modules/tun.ko 2>/dev/null || modprobe tun 2>/dev/null
    if [ ! -c /dev/net/tun ]; then mkdir -p /dev/net && mknod /dev/net/tun c 10 200; fi
    chmod 0666 /dev/net/tun 2>/dev/null
}

ensure_caps() {
    d=$(daemon_path)
    plain_file "$d" || return
    sig=$(stat -c '%i:%Y:%s' "$d")
    if [ "$(cat "$MARK" 2>/dev/null)" = "$sig" ] && getcap "$d" | grep -q cap_net_admin && [ "$(stat -c %a "$d")" = 700 ]; then return; fi
    # File capabilities apply to whoever runs the file: only the package user may.
    chmod 0700 "$d"
    if setcap cap_net_admin,cap_net_raw=ep "$d" && [ "$(stat -c '%i:%Y:%s' "$d")" = "$sig" ] && plain_file "$d"; then
        echo "$sig" > "$MARK" && chmod 0644 "$MARK"
        log "capabilities granted to $d"
    else
        setcap -r "$d" 2>/dev/null
        log "could not grant capabilities to $d"
    fi
}

migrate() {
    [ -e "$HOME_DIR/identity.secret" ] && return
    g=$(id -gn "$PKG_USER") || return
    d=$(daemon_path)
    for old in $OLD_DIRS; do
        plain_file "$old/identity.secret" || continue
        if ps -eo args | grep '[z]erotier-one' | grep -v "^$d" | grep -q .; then
            log "migration waits: another zerotier-one is running with an identity"
            return
        fi
        install -o "$PKG_USER" -g "$g" -m 0644 "$old/identity.public" "$HOME_DIR/identity.public"
        install -o "$PKG_USER" -g "$g" -m 0600 "$old/identity.secret" "$HOME_DIR/identity.secret"
        plain_file "$old/local.conf" && install -o "$PKG_USER" -g "$g" -m 0644 "$old/local.conf" "$HOME_DIR/local.conf"
        for sub in networks.d moons.d; do
            [ -d "$old/$sub" ] || continue
            install -d -o "$PKG_USER" -g "$g" -m 0755 "$HOME_DIR/$sub"
            for f in "$old/$sub"/*; do
                plain_file "$f" && install -o "$PKG_USER" -g "$g" -m 0644 "$f" "$HOME_DIR/$sub/"
            done
        done
        log "migrated identity $(cut -c1-10 "$HOME_DIR/identity.public") from $old"
        return
    done
}

ensure_owner() {
    uid=$(id -u "$PKG_USER") || return
    g=$(id -gn "$PKG_USER")
    for f in identity.public identity.secret; do
        p="$HOME_DIR/$f"
        if plain_file "$p" && [ "$(stat -c %u "$p")" != "$uid" ]; then
            chown -h "$PKG_USER:$g" "$p" && log "owner of $f set to $PKG_USER"
        fi
    done
    plain_file "$HOME_DIR/identity.secret" && chmod 0600 "$HOME_DIR/identity.secret"
}

LAST_START=0
ensure_running() {
    st=$(synopkg status "$PKG" 2>/dev/null)
    case "$st" in *'"status":"running"'*) return ;; esac
    [ -f "$PKG_DIR/enabled" ] || echo "$st" | grep -q '"start_failed"' || return
    now=$(date +%s)
    [ $((now - LAST_START)) -lt 60 ] && return
    LAST_START=$now
    if synopkg start "$PKG" >/dev/null 2>&1; then log "started $PKG"; else log "start of $PKG failed, see $HOME_DIR/$PKG.log"; fi
}

if [ -f "$PIDF" ] && kill -0 "$(cat "$PIDF")" 2>/dev/null; then exit 0; fi
echo $$ > "$PIDF"
log "guard v${GUARD_VERSION} started"
absent=0
while :; do
    if installed; then
        absent=0
        ensure_tun
        ensure_caps
        migrate
        ensure_owner
        ensure_running
    else
        absent=$((absent + 1))
        if [ "$absent" -gt 60 ]; then log "$PKG not installed for 30 minutes, guard exits"; rm -f "$PIDF"; exit 0; fi
    fi
    sleep 30
done
`;
}

/** The command line of the boot-up task: write the guard to /run and start it detached. */
export function taskOperation(options: GuardOptions): string {
  const runPath = `/run/${options.pkg}-guard.sh`;
  return [
    `cat > ${runPath} <<'${HEREDOC}'`,
    guardScript(options).trimEnd(),
    HEREDOC,
    `chmod 0700 ${runPath}`,
    `setsid /bin/sh ${runPath} </dev/null >/dev/null 2>&1 &`,
    'exit 0',
  ].join('\n');
}
