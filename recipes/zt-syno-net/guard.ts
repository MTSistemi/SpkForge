import { createHash } from 'node:crypto';

// The root guard of zt-syno-net and the DSM boot-up task that runs it.
//
// DSM 7 refuses any root step or file capability in a third-party package
// ("ctrl-script and executable section should not exist", "tool capabilities
// should not exist"), so the only root actor is a Task Scheduler task. The
// install wizard creates it through the admin's own DSM session.
//
// Security rule: root never executes a file the package user can modify. The
// whole guard script is stored inside the task (DSM keeps it root-owned); at
// boot the task writes it to /run (root-owned tmpfs) and starts it there. The
// guard never follows symlinks inside the package's directories.
//
// DSM refuses any task command that contains a percent sign (EventScheduler
// create answers error 117), so the guard builds it at run time:
// P=$(printf '\045') and uses \${P} in date and stat formats.
//
// Every 5 seconds the guard (cheap checks, so an upgrade waits seconds, not half
// a minute, for the capability; ZeroTier is down meanwhile):
//   - migrates the identity of an older ZeroTier package once, as soon as no
//     other zerotier-one runs; while it waits, /run/<pkg>.migrating exists and
//     the package must not start (zerotier-one would create a new identity, and
//     the node would come up under an address unknown to its networks);
//   - loads tun and makes /dev/net/tun usable;
//   - grants CAP_NET_ADMIN/CAP_NET_RAW to the package's zerotier-one when it is
//     new (install, upgrade) and records it in /run/<pkg>.caps for the package.
// Every 30 seconds it also:
//   - keeps the identity owned by the package user;
//   - starts the package when DSM wants it running and it is not.

export interface GuardOptions {
  /** Package name, e.g. "zt-syno-net". */
  pkg: string;
  /** Package user from conf/privilege, e.g. "zt-syno-net" or "sc-zerotier-one". */
  user: string;
  /** Path of the zerotier-one executable, or "per-family" for zerotier-one-<family> picked by uname -m. */
  daemon: 'per-family' | string;
}

export const GUARD_VERSION = 5;
/** The boot-up task is named after the package; this is the SpkForge build's. */
export const TASK_NAME = 'zt-syno-net';
const HEREDOC = 'ZT_SYNO_NET_GUARD_EOF';

/**
 * ZeroTier packages whose identity the guard takes over: the old community
 * "zerotier" package, and the two builds of this one (SpkForge "zt-syno-net",
 * SynoCommunity "zerotier-one"), so a NAS can move between them and keep its
 * node ID. The package's own directory is left out. Both paths of each: the
 * /var/packages link while the package is installed, and its data directory,
 * which DSM keeps after an uninstall.
 *
 * The first directory with an identity wins, so the newest source comes first:
 * the other build of this package, then the old "zerotier" one. Seen on a NAS
 * that went zerotier -> zt-syno-net -> zerotier-one: with "zerotier" first, the
 * networks came from its 2025 directory instead of from zt-syno-net's.
 */
const KNOWN_PACKAGES = ['zt-syno-net', 'zerotier-one', 'zerotier'];

export function oldDirs(options: GuardOptions): string[] {
  return KNOWN_PACKAGES.filter((p) => p !== options.pkg)
    .flatMap((p) => [`/var/packages/${p}/var`, `/volume1/@appdata/${p}`]);
}

function daemonResolver(options: GuardOptions): string {
  if (options.daemon !== 'per-family') return `echo "${options.daemon}"`;
  return [
    'case "$(uname -m)" in',
    '        x86_64|amd64) f=x86_64 ;; aarch64|arm64|armv8*) f=armv8 ;;',
    '        armv7*|armv6*|arm) f=armv7 ;; i686|i586|i486|i386|x86) f=i686 ;; *) f=unknown ;;',
    '    esac',
    '    echo "$TARGET/bin/zerotier-one-$f"',
  ].join('\n');
}

export function guardScript(options: GuardOptions): string {
  return `#!/bin/sh
# ${options.pkg} guard v${GUARD_VERSION} (root). Generated by SpkForge, installed by the
# "${options.pkg}" boot-up task. https://github.com/MTSistemi/SpkForge
PKG="${options.pkg}"
PKG_USER="${options.user}"
PKG_DIR="/var/packages/$PKG"
TARGET="$PKG_DIR/target"
HOME_DIR="$PKG_DIR/var"
MARK="/run/$PKG.caps"
LOG="/var/log/$PKG-guard.log"
PIDF="/run/$PKG-guard.pid"
VERF="/run/$PKG-guard.ver"
MIGRATING="/run/$PKG.migrating"
OLD_DIRS="${oldDirs(options).join(' ')}"
export PATH=/sbin:/bin:/usr/sbin:/usr/bin:/usr/syno/sbin:/usr/syno/bin
# A literal percent sign is not allowed in a DSM task command: build it.
P=$(printf '\\045')

log() {
    echo "$(date "+\${P}Y-\${P}m-\${P}d \${P}H:\${P}M:\${P}S") $*" >> "$LOG"
    if [ "$(wc -l < "$LOG")" -gt 500 ]; then tail -n 300 "$LOG" > "$LOG.tmp" && mv -f "$LOG.tmp" "$LOG"; fi
}

daemon_path() {
    ${daemonResolver(options)}
}

installed() { [ -f "$PKG_DIR/INFO" ] && [ -d "$TARGET/bin" ]; }

plain_file() { [ -f "$1" ] && [ ! -L "$1" ]; }

ensure_tun() {
    lsmod | grep -qw tun || insmod /lib/modules/tun.ko 2>/dev/null || modprobe tun 2>/dev/null
    if [ ! -c /dev/net/tun ]; then mkdir -p /dev/net && mknod /dev/net/tun c 10 200; fi
    chmod 0666 /dev/net/tun 2>/dev/null
}

ensure_caps() {
    d=$(daemon_path)
    plain_file "$d" || return
    sig=$(stat -c "\${P}i:\${P}Y:\${P}s" "$d")
    if [ "$(cat "$MARK" 2>/dev/null)" = "$sig" ] && getcap "$d" | grep -q cap_net_admin && [ "$(stat -c "\${P}a" "$d")" = 700 ]; then return; fi
    # File capabilities apply to whoever runs the file: only the package user may.
    chmod 0700 "$d"
    if setcap cap_net_admin,cap_net_raw=ep "$d" && [ "$(stat -c "\${P}i:\${P}Y:\${P}s" "$d")" = "$sig" ] && plain_file "$d"; then
        echo "$sig" > "$MARK" && chmod 0644 "$MARK"
        log "capabilities granted to $d"
    else
        setcap -r "$d" 2>/dev/null
        log "could not grant capabilities to $d"
    fi
}

# A zerotier-one process other than this package's own. Matched on the
# process name and the executable, never on command lines: the shell running
# the boot-up task carries the whole guard text, "zerotier-one" included.
other_daemon() {
    # /proc/<pid>/exe is the resolved path; target/ is a symlink to @appstore.
    d=$(readlink -f "$(daemon_path)")
    for c in /proc/[0-9]*/comm; do
        case "$(cat "$c" 2>/dev/null)" in zerotier-one*) ;; *) continue ;; esac
        [ "$(readlink "$(dirname "$c")/exe" 2>/dev/null)" = "$d" ] && continue
        return 0
    done
    return 1
}

WAIT_LOGGED=0
migrate() {
    if [ -e "$HOME_DIR/identity.secret" ]; then rm -f "$MIGRATING"; return; fi
    pending=0
    for old in $OLD_DIRS; do plain_file "$old/identity.secret" && pending=1; done
    if [ "$pending" = 0 ]; then rm -f "$MIGRATING"; return; fi
    # Tell the package not to start yet (see the header).
    [ -e "$MIGRATING" ] || { : > "$MIGRATING"; chmod 0644 "$MIGRATING"; }
    g=$(id -gn "$PKG_USER") || return
    for old in $OLD_DIRS; do
        plain_file "$old/identity.secret" || continue
        if other_daemon; then
            [ "$WAIT_LOGGED" = 1 ] || log "migration waits: another zerotier-one is running with an identity"
            WAIT_LOGGED=1
            return
        fi
        install -o "$PKG_USER" -g "$g" -m 0644 "$old/identity.public" "$HOME_DIR/identity.public"
        install -o "$PKG_USER" -g "$g" -m 0600 "$old/identity.secret" "$HOME_DIR/identity.secret"
        plain_file "$old/local.conf" && install -o "$PKG_USER" -g "$g" -m 0644 "$old/local.conf" "$HOME_DIR/local.conf"
        for sub in networks.d moons.d; do
            [ -d "$old/$sub" ] || continue
            install -d -o "$PKG_USER" -g "$g" -m 0755 "$HOME_DIR/$sub"
            for f in "$old/$sub"/*; do
                plain_file "$f" && install -o "$PKG_USER" -g "$g" -m 0644 "$f" "$HOME_DIR/$sub/"
            done
        done
        log "migrated identity $(cut -c1-10 "$HOME_DIR/identity.public") from $old"
        rm -f "$MIGRATING"
        WAIT_LOGGED=0
        return
    done
}

ensure_owner() {
    uid=$(id -u "$PKG_USER") || return
    g=$(id -gn "$PKG_USER")
    for f in identity.public identity.secret; do
        p="$HOME_DIR/$f"
        if plain_file "$p" && [ "$(stat -c "\${P}u" "$p")" != "$uid" ]; then
            chown -h "$PKG_USER:$g" "$p" && log "owner of $f set to $PKG_USER"
        fi
    done
    plain_file "$HOME_DIR/identity.secret" && chmod 0600 "$HOME_DIR/identity.secret"
}

LAST_START=0
ensure_running() {
    st=$(synopkg status "$PKG" 2>/dev/null)
    case "$st" in *'"status":"running"'*) return ;; esac
    [ -e "$MIGRATING" ] && return
    [ -f "$PKG_DIR/enabled" ] || echo "$st" | grep -q '"start_failed"' || return
    now=$(date "+\${P}s")
    [ $((now - LAST_START)) -lt 60 ] && return
    LAST_START=$now
    if synopkg start "$PKG" >/dev/null 2>&1; then log "started $PKG"; else log "start of $PKG failed, see $HOME_DIR/$PKG.log"; fi
}

# One guard at a time. A guard of another build (the task was just updated)
# hands over: it is stopped and this one takes its place. The pid is checked
# against /proc first, so a recycled pid never kills an unrelated process.
old=$(cat "$PIDF" 2>/dev/null)
if [ -n "$old" ] && [ "$old" != "$$" ] && tr '\\000' ' ' < "/proc/$old/cmdline" 2>/dev/null | grep -q "$PKG-guard.sh"; then
    if [ "$(cat "$VERF" 2>/dev/null)" = "$(cksum < "$0")" ]; then exit 0; fi
    kill "$old" 2>/dev/null
    sleep 1
    kill -9 "$old" 2>/dev/null
    log "replaced the guard of another build (pid $old)"
fi
echo $$ > "$PIDF"
cksum < "$0" > "$VERF"
# setsid leaves the session, not the cgroup: started by the install wizard the
# guard sits in the cgroup of DSM's web server, started by hand in that of the
# shell's service (seen: the hypervisor guest agent's), and systemd kills the
# whole cgroup when that service stops or restarts. Move to the root cgroup of
# every hierarchy, where only a reboot ends the guard.
for r in $(awk '$3 == "cgroup" { print $2 }' /proc/mounts); do echo $$ > "$r/cgroup.procs" 2>/dev/null; done
log "guard v${GUARD_VERSION} started"
absent=0
# Heavier checks every 6 rounds (30 s), counted: no modulo sign in a task command.
round=6
while :; do
    if installed; then
        absent=0
        # Before the capability: the package waits for it, so by the time it
        # may start the migration marker is already in place.
        migrate
        ensure_tun
        ensure_caps
        round=$((round + 1))
        if [ "$round" -ge 6 ]; then
            round=0
            ensure_owner
            ensure_running
        fi
    else
        absent=$((absent + 1))
        if [ "$absent" -gt 360 ]; then log "$PKG not installed for 30 minutes, guard exits"; rm -f "$PIDF"; exit 0; fi
    fi
    sleep 5
done
`;
}

/** The launcher shipped in the package as bin/zt-syno-net-guard, for the manual setup only. */
export function launcherFile(options: GuardOptions): string {
  return `#!/bin/sh
${taskOperation(options)}
`;
}

/**
 * The command for a hand-made boot-up task. Root must never run a file the
 * package user can change, so it copies the launcher to /run (root-only), checks
 * the copy against the SHA-256 of this exact build and only then runs it.
 * No percent sign: DSM refuses it in a task command.
 */
export function manualCommand(options: GuardOptions, launcherPath: string): string {
  const sha = createHash('sha256').update(launcherFile(options)).digest('hex');
  const copy = `/run/${options.pkg}-launch.sh`;
  return `cp ${launcherPath} ${copy} && chmod 0700 ${copy} && echo "${sha}  ${copy}" | sha256sum -c --status && /bin/sh ${copy}`;
}

/** The command line of the boot-up task: write the guard to /run and start it detached. */
export function taskOperation(options: GuardOptions): string {
  const runPath = `/run/${options.pkg}-guard.sh`;
  return [
    `cat > ${runPath} <<'${HEREDOC}'`,
    guardScript(options).trimEnd(),
    HEREDOC,
    `chmod 0700 ${runPath}`,
    `setsid /bin/sh ${runPath} </dev/null >/dev/null 2>&1 &`,
    'exit 0',
  ].join('\n');
}
